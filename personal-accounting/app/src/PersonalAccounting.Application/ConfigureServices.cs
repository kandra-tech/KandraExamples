using PersonalAccounting.Application.Accounting;
using PersonalAccounting.Application.Constants;
using PersonalAccounting.Application.Navigation;
using PersonalAccounting.Application.Printing;
using PersonalAccounting.Application.Scheduling;
using PersonalAccounting.Application.Seeding;
using PersonalAccounting.Application.Services;
using PersonalAccounting.Domain.Identity;
using PersonalAccounting.Forms.DataProcessors;
using Microsoft.Extensions.DependencyInjection;

namespace PersonalAccounting.Application;

public static class ConfigureServices
{
    public static void AddPersonalAccountingApplication(this IServiceCollection services)
    {
        services.AddScoped<ICurrencyConversionService, CurrencyConversionService>();
        services.AddValidatorsFromAssembly(Assembly.GetExecutingAssembly());
        // The shared, localizable {X}Validator classes live in PersonalAccounting.Forms (referenced by both
        // server and client); without this a Dto's validator is never registered and the host fails its
        // service validation at startup (CompanySettingsValidator is the first one).
        services.AddValidatorsFromAssembly(typeof(CompanySettingsValidator).Assembly);

        // AddLocalization() + the platform localization module are registered by
        // Kandra.Application.AddKandraApplication<> (called before this method, via
        // Kandra.Api.Lib.AddKandra<> in PersonalAccounting.WebApi/Program.cs) - only the config-specific
        // module needs registering here, after the platform module so it wins the composite chain per key.
        services.AddLocalizationModule<PersonalAccounting.Localization.PersonalAccounting>();

        // dictionaries + documents + reports + data processors (repository/behavior wiring): generated
        // from the Kandra*Entity/Kandra*Form/Kandra*Behavior attributes by Kandra.Generators.Di.Application
        // - a no-op today since this configuration has none yet.
        services.AddGeneratedPersonalAccountingApplicationEntities();

        // Keyed IEntityOperationAdapter registration per Document/Dictionary/Report/DataProcessor entity plus the
        // entity catalog, generated by Kandra.Generators.EntityOperations - a no-op today. The data importer (demo
        // seeding, the Data import admin page) dispatches onto these adapters.
        services.AddGeneratedPersonalAccountingEntityAdapters();
        services.AddKandraEntityOperations<GeneratedPersonalAccountingEntityCatalog>();
        services.AddKandraDataImport("PersonalAccounting");

        // Import packages embedded under ImportPackages/ (this configuration's demo data lives in
        // personalaccounting-demo.json, a package with no steps yet) - listed and run from the Data import admin page.
        services.AddImportPackages(typeof(ConfigureServices).Assembly);

        // Demo installations: applies the embedded demo package, creates the demo users, keeps demo content current
        // after an update. See PersonalAccountingDemoUsers for the free-tier limits the sample users must respect.
        services.AddSingleton<IDemoUserProvider, PersonalAccountingDemoUsers>();
        services.AddKandraDemoSeeding<DomainUser, DomainRole>();

        // print/export renderers for every [PrintForm] class: generated by Kandra.Generators.Printing - a
        // no-op today. The platform renderer resolver + CSV/PDF targets (AddKandraPrinting) are registered
        // by Kandra.Application.AddKandraApplication<> instead.
        services.AddGeneratedPersonalAccountingPrintRenderers();

        // The company letterhead of every [PrintForm] with Frame = Letterhead, read from the Company* constants (set them
        // on the Company settings data processor). Registered here, after AddKandraPrinting() above, so it replaces the
        // engine's no-letterhead default - the last registration wins.
        services.AddScoped<IPrintFrameProvider, PersonalAccountingPrintFrameProvider>();

        services.AddScoped<IClaimsSeeder, PersonalAccountingClaimsSeeder>();

        // Discoverable entity/behavior half of "all claims": generated by Kandra.Generators.Di.Application
        // - a no-op today. Kandra.Application's own AddKandraApplication<> registers the (engine-generic)
        // IClaimsCatalog that composes this with the area-wildcard claims.
        services.AddGeneratedPersonalAccountingEntityClaimsBuilder();

        // Chart-of-accounts/posting subsystem - the concrete chart is the one application-specific piece;
        // everything else is registered by Kandra.Application/Kandra.Persistence's own
        // AddKandraApplication/AddKandraPersistence.
        services.AddSingleton<IChartOfAccountsBuilder, PersonalAccountingChartOfAccountsBuilder>();

        services.AddSingleton<IConstantRegistry, GeneratedConstantRegistry>();
        services.AddSingleton<IDataProcessorRegistry, GeneratedDataProcessorRegistry>();

        // Interface navigation trees (docs the server-driven NavMenu reads) - the mandatory default. First
        // (only, today) registration wins as the default - see AddKandraInterface's own doc comment.
        services.AddKandraInterface(PersonalAccountingInterfaces.Default);
    }
}
